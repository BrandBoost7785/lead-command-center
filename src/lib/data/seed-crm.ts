export interface CrmBundle {
  companies: Company[];
  contacts: Contact[];
  prospects: Prospect[];
  communications: Communication[];
}

export function buildCrm(now: number): CrmBundle {
  const companies = buildCompanies(now);
  const contacts: Contact[] = [];
  const prospects: Prospect[] = [];
  const communications: Communication[] = [];

  const specs: ProspectSpec[] = [...P1, ...P2];
  let colorIdx = 0;
  let commIdx = 0;

  for (const spec of specs) {
    const businessId =
      spec.id.startsWith("p_angela") || P2.some((p) => p.id === spec.id) ? BIZ2 : BIZ1;
    const contactId = spec.id.replace("p_", "ct_");
    const lastComm = spec.h.reduce((acc, c) => (c.m < acc.m ? c : acc), spec.h[0]);
    const lastInbound = spec.h.filter((c) => c.dir === "in").sort((a, b) => a.m - b.m)[0];
    const lastOutbound = spec.h.filter((c) => c.dir === "out").sort((a, b) => a.m - b.m)[0];
    const avgResponse = (() => {
      const withResp = spec.h.filter((c) => c.dir === "in" && c.respMin);
      if (!withResp.length) return undefined;
      return Math.round(withResp.reduce((s, c) => s + (c.respMin ?? 0), 0) / withResp.length);
    })();

    contacts.push({
      id: contactId,
      tenantId: TENANT,
      businessId,
      companyId: spec.company,
      firstName: spec.first,
      lastName: spec.last,
      email: spec.email,
      phone: spec.phone,
      whatsapp: spec.preferred === "whatsapp" ? spec.phone : undefined,
      linkedin: spec.linkedin,
      jobTitle: spec.title,
      location: spec.location,
      avatarColor: COLORS[colorIdx++ % COLORS.length],
      createdAt: new Date(now - (oldestMinutes(spec.h) + 60) * 60_000).toISOString(),
      lastSeenAt: new Date(now - lastComm.m * 60_000).toISOString(),
      preferredChannel: spec.preferred,
      tags: spec.tags ?? [],
    });

    for (const extra of spec.extraContacts ?? []) {
      contacts.push({
        id: extra.id,
        tenantId: TENANT,
        businessId,
        companyId: spec.company,
        firstName: extra.first,
        lastName: extra.last,
        email: extra.email,
        jobTitle: extra.title,
        location: spec.location,
        avatarColor: COLORS[colorIdx++ % COLORS.length],
        createdAt: new Date(now - 120 * 86_400_000).toISOString(),
        lastSeenAt: new Date(now - 4 * 86_400_000).toISOString(),
        tags: [],
      });
    }

    prospects.push({
      id: spec.id,
      tenantId: TENANT,
      businessId,
      contactId,
      companyId: spec.company,
      ownerId: spec.owner,
      source: spec.source,
      state: spec.state,
      stateInferred: true,
      score: 0, // computed by the scoring engine on load
      scoreDelta: 0,
      intent: spec.intent,
      intentConfidence: 0.72 + (spec.engagement % 20) / 100,
      engagement: spec.engagement,
      priority: "medium",
      value: spec.value,
      lastActivityAt: new Date(now - lastComm.m * 60_000).toISOString(),
      lastInboundAt: lastInbound ? new Date(now - lastInbound.m * 60_000).toISOString() : undefined,
      lastOutboundAt: lastOutbound
        ? new Date(now - lastOutbound.m * 60_000).toISOString()
        : undefined,
      firstResponseMinutes: avgResponse,
      daysSinceContact: Math.floor(lastComm.m / (60 * 24)),
      tags: spec.tags ?? [],
      createdAt: new Date(now - (oldestMinutes(spec.h) + 60) * 60_000).toISOString(),
      updatedAt: new Date(now - lastComm.m * 60_000).toISOString(),
      healthFlags: spec.flags ?? [],
      summary: spec.summary,
      researchNotes: spec.research,
      doNotContact: spec.doNotContact,
      nextActionAt: undefined,
      nextActionType: undefined,
    });

    // Communications — newest first in the spec, stored chronologically per thread
    for (const c of spec.h) {
      const id = `com_${spec.slug}_${commIdx++}`;
      const occurredAt = new Date(now - c.m * 60_000).toISOString();
      const isInbound = c.dir === "in";
      const intent = c.intent ?? (isInbound ? "neutral" : undefined);
      const enrichment: CommunicationEnrichment | undefined = intent
        ? {
            intent,
            intentConfidence: 0.74 + (c.m % 17) / 100,
            sentiment: c.sentiment ?? INTENT_SENTIMENT[intent],
            urgency: c.urgency ?? INTENT_URGENCY[intent],
            topics: c.topics ?? INTENT_TOPICS[intent],
            requiredAction: INTENT_ACTION[intent] ?? undefined,
            summary: summarise(c.body),
            entities: buildEntities(c),
            model: "lead-intel/classifier-1",
            enrichedAt: new Date(now - c.m * 60_000 + 45_000).toISOString(),
          }
        : undefined;

      communications.push({
        id,
        tenantId: TENANT,
        businessId,
        prospectId: spec.id,
        contactId,
        companyId: spec.company,
        channel: c.ch,
        direction: isInbound ? "inbound" : "outbound",
        status: c.st,
        subject: c.subject,
        body: c.body,
        preview: summarise(c.body, 140),
        occurredAt,
        actorId: isInbound ? contactId : (c.actor ?? spec.owner),
        actorKind: isInbound
          ? "contact"
          : c.actor?.startsWith("u_ava") || c.actor?.startsWith("u_nina")
            ? "ai"
            : "user",
        threadId: `th_${spec.slug}`,
        enrichment,
        handled: c.handled ?? !isInbound,
        requiresResponse: c.requiresResponse ?? (isInbound && c.ch === "email"),
        respondedAt: c.respMin
          ? new Date(now - c.m * 60_000 + c.respMin * 60_000).toISOString()
          : undefined,
        responseTimeMinutes: c.respMin,
        call:
          c.ch === "call" || c.ch === "meeting"
            ? {
                durationSeconds: c.dur ?? 0,
                direction: isInbound ? "inbound" : "outbound",
                outcome: c.outcome ?? "no_answer",
                summary: c.dur && c.dur > 0 ? callSummary(c.body, c.dur) : undefined,
                transcript:
                  c.dur && c.dur > 300 ? buildTranscript(spec.first, c.dur, c.body) : undefined,
                objections:
                  c.intent === "objection"
                    ? ["Termination clause length", "Budget timing"]
                    : undefined,
              }
            : undefined,
        attachments: c.attachments?.map((a, i) => ({ id: `att_${id}_${i}`, ...a })),
        tags: [],
      } as Communication);
    }
  }

  return { companies, contacts, prospects, communications };
}

function oldestMinutes(h: { m: number }[]): number {
  return h.reduce((max, c) => Math.max(max, c.m), 0);
}

function summarise(body: string, max = 120): string {
  const clean = body.replace(/\s+/g, " ").trim();
  return clean.length <= max ? clean : `${clean.slice(0, max - 1)}…`;
}

function callSummary(body: string, duration: number): string {
  return `${body} Duration ${Math.round(duration / 60)}m ${duration % 60}s. Connection quality good.`;
}

function buildTranscript(
  firstName: string,
  duration: number,
  context: string,
): NonNullable<Communication["call"]>["transcript"] {
  const segs: { at: number; speaker: "contact" | "agent"; text: string }[] = [
    {
      at: 5,
      speaker: "agent",
      text: `Thanks for making the time, ${firstName}. I'll keep this to about ten minutes.`,
    },
    { at: 38, speaker: "contact", text: context },
    {
      at: 150,
      speaker: "agent",
      text: "That's a fair point — let me walk you through how that works in practice, and what it costs.",
    },
    {
      at: 320,
      speaker: "contact",
      text: "Okay, that's helpful. Send it over and I'll take it to the team.",
    },
    {
      at: duration - 40,
      speaker: "agent",
      text: "Will do. I'll follow up Thursday with the summary and next steps.",
    },
  ];
  return segs.filter((s) => s.at < duration);
}

function buildEntities(c: CommSpec): { type: string; value: string }[] {
  const out: { type: string; value: string }[] = [];
  const money = c.body.match(/\$[\d,]+|\d+%/g);
  if (money) money.slice(0, 2).forEach((m) => out.push({ type: "metric", value: m }));
  const days = c.body.match(/\b(Mon|Tues|Wednes|Thurs|Fri|Satur|Sun)day\b/gi);
  if (days) days.slice(0, 2).forEach((d) => out.push({ type: "date", value: d }));
  if (/contract|proposal|clause|terms/i.test(c.body))
    out.push({ type: "document", value: "commercial terms" });
  if (out.length === 0) out.push({ type: "topic", value: (c.topics ?? ["general"])[0] });
  return out;
}
